<?php
/**
 * Dynamic Brand CSS Updater
 * This script updates the brand-colors.css file with current color settings
 */

// Include necessary files
require_once __DIR__ . '/../includes/db.php';
require_once __DIR__ . '/../includes/helpers.php';

// Get current brand colors from database
function getBrandColors() {
    $db = $GLOBALS['db'] ?? $mysqli ?? null;
    if (!$db) return null;
    
    $colors = [
        'primary' => '#fd7e14',
        'secondary' => '#6c757d', 
        'accent' => '#0d6efd'
    ];
    
    try {
        // Get brand colors from settings
        $stmt = $db->prepare("SELECT `key`, `value` FROM settings WHERE `key` IN ('brand_primary_color', 'brand_secondary_color', 'brand_accent_color')");
        $stmt->execute();
        $result = $stmt->get_result();
        
        while ($row = $result->fetch_assoc()) {
            $key = str_replace('_color', '', $row['key']);
            if (isset($colors[$key])) {
                $colors[$key] = $row['value'];
            }
        }
        $stmt->close();
    } catch (Exception $e) {
        error_log("Error getting brand colors: " . $e->getMessage());
    }
    
    return $colors;
}

// Convert hex to RGB
function hexToRgb($hex) {
    $hex = ltrim($hex, '#');
    if (strlen($hex) === 3) {
        $hex = $hex[0] . $hex[0] . $hex[1] . $hex[1] . $hex[2] . $hex[2];
    }
    
    $r = hexdec(substr($hex, 0, 2));
    $g = hexdec(substr($hex, 2, 2));
    $b = hexdec(substr($hex, 4, 2));
    
    return "$r, $g, $b";
}

