// Update CSS file
function updateBrandCSS($colors) {
    $cssPath = __DIR__ . '/../assets/css/brand-colors.css';
    $cssContent = generateBrandCSS($colors);
    
    // Create backup of existing file
    if (file_exists($cssPath)) {
        $backupPath = str_replace('.css', '-' . date('Y-m-d-H-i-s') . '.css', $cssPath);
        copy($cssPath, $backupPath);
    }
    
    // Write new CSS content
    if (file_put_contents($cssPath, $cssContent)) {
        return true;
    }
    
    return false;
}

// Main execution
if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    // Handle AJAX request from admin
    $colors = getBrandColors();
    
    if ($colors) {
        if (updateBrandCSS($colors)) {
            header('Content-Type: application/json');
            echo json_encode([
                'success' => true,
                'message' => 'Brand CSS updated successfully',
                'colors' => $colors
            ]);
        } else {
            header('Content-Type: application/json');
            echo json_encode([
                'success' => false,
                'message' => 'Failed to update CSS file'
            ]);
        }
    } else {
        header('Content-Type: application/json');
        echo json_encode([
            'success' => false,
            'message' => 'No colors found in database'
        ]);
    }
} else {
    // Direct access - update with current database colors
    $colors = getBrandColors();
    if ($colors && updateBrandCSS($colors)) {
        echo "✅ Brand CSS updated successfully!\n";
        echo "Colors: " . json_encode($colors) . "\n";
        echo "File: assets/css/brand-colors.css\n";
    } else {
        echo "❌ Failed to update brand CSS\n";
    }
}
